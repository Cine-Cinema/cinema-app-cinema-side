package com.cinemaapp.cinema.entity;

import jakarta.persistence.*;

/**
 * JPA entity representing the cinema manager account stored in the {@code cinema} table.
 *
 * <p>This project models a single-cinema system, so {@code AuthService} enforces that
 * only one {@code Cinema} account is registered. The entity holds login credentials
 * (email and BCrypt-hashed password) as well as basic venue profile information.
 *
 * <p>{@link Entity} marks this class as a persistent domain object managed by JPA/Hibernate,
 * and {@link Table} maps it explicitly to the PostgreSQL {@code cinema} table.
 */
@Entity
@Table(name = "cinema")
public class Cinema {

    /**
     * Surrogate primary key generated by PostgreSQL {@code BIGSERIAL} ({@code IDENTITY} strategy).
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(nullable = false, length = 100)
    private String name;

    @Column(length = 200)
    private String address;

    /** Unique login identifier; normalized to lowercase by {@code AuthService} and {@code CinemaProfileService}. */
    @Column(nullable = false, unique = true, length = 100)
    private String email;

    /** Stores the BCrypt password hash (never raw plain-text) produced by {@code PasswordEncoder}. */
    @Column(nullable = false, length = 100)
    private String password;

    /** Required no-argument constructor used by JPA/Hibernate when instantiating entities from database rows. */
    public Cinema() {
    }

    public Long getId() {
        return id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getAddress() {
        return address;
    }

    public void setAddress(String address) {
        this.address = address;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getPassword() {
        return password;
    }

    public void setPassword(String password) {
        this.password = password;
    }
}