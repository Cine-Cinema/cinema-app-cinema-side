package com.cinemaapp.cinema.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.persistence.UniqueConstraint;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.LocalTime;

/**
 * JPA entity representing a scheduled movie screening in the {@code showtime} table.
 *
 * <p>Because the cinema has a single hall, two screenings cannot share the same
 * {@code (show_date, show_time)} start slot (enforced by {@code uq_showtime_date_time}
 * in the database) or overlap in duration (enforced in {@code ShowtimeService}).
 */
@Entity
@Table(
        name = "showtime",
        uniqueConstraints = {
                @UniqueConstraint(
                        name = "uq_showtime_date_time",
                        columnNames = {"show_date", "show_time"}
                )
        }
)
public class Showtime {

    /** Primary key generated by PostgreSQL {@code BIGSERIAL}. */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /** Foreign key ID referencing {@code movie(id)} (stored as a scalar ID rather than a {@code @ManyToOne} association). */
    @Column(name = "movie_id", nullable = false)
    private Long movieId;

    @Column(name = "show_date", nullable = false)
    private LocalDate showDate;

    @Column(name = "show_time", nullable = false)
    private LocalTime showTime;

    /** Ticket price using {@link BigDecimal} with 10 total digits and 2 decimal places for exact currency arithmetic. */
    @Column(
            name = "price",
            nullable = false,
            precision = 10,
            scale = 2
    )
    private BigDecimal price;

    /** Total number of seats available in the hall for this screening. */
    @Column(name = "total_seats", nullable = false)
    private Integer totalSeats;

    /** Seating layout hint indicating how many seats appear in each row. */
    @Column(name = "seats_per_row", nullable = false)
    private Integer seatsPerRow;

    /** Controls whether the showtime is active for bookings; new showtimes default to {@code true}. */
    @Column(name = "active", nullable = false)
    private boolean active = true;

    public Showtime() {
    }

    public Showtime(
            Long movieId,
            LocalDate showDate,
            LocalTime showTime,
            BigDecimal price,
            Integer totalSeats,
            Integer seatsPerRow
    ) {
        this.movieId = movieId;
        this.showDate = showDate;
        this.showTime = showTime;
        this.price = price;
        this.totalSeats = totalSeats;
        this.seatsPerRow = seatsPerRow;
        this.active = true;
    }

    public Long getId() {
        return id;
    }

    public Long getMovieId() {
        return movieId;
    }

    public void setMovieId(Long movieId) {
        this.movieId = movieId;
    }

    public LocalDate getShowDate() {
        return showDate;
    }

    public void setShowDate(LocalDate showDate) {
        this.showDate = showDate;
    }

    public LocalTime getShowTime() {
        return showTime;
    }

    public void setShowTime(LocalTime showTime) {
        this.showTime = showTime;
    }

    public BigDecimal getPrice() {
        return price;
    }

    public void setPrice(BigDecimal price) {
        this.price = price;
    }

    public Integer getTotalSeats() {
        return totalSeats;
    }

    public void setTotalSeats(Integer totalSeats) {
        this.totalSeats = totalSeats;
    }

    public Integer getSeatsPerRow() {
        return seatsPerRow;
    }

    public void setSeatsPerRow(Integer seatsPerRow) {
        this.seatsPerRow = seatsPerRow;
    }

    public boolean isActive() {
        return active;
    }

    public void setActive(boolean active) {
        this.active = active;
    }
}