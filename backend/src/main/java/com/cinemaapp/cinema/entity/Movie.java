package com.cinemaapp.cinema.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

/**
 * JPA entity representing a movie catalog entry in the {@code movie} table.
 *
 * <p>Movies are referenced by {@link MovieImage} (via shared {@code movie_id}) and by
 * {@link Showtime} (via {@code movie_id}) to calculate screening end times from
 * {@code durationMinutes}.
 */
@Entity
@Table(name = "movie")
public class Movie {

    /** Primary key generated by PostgreSQL {@code BIGSERIAL}. */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(name = "title", nullable = false, length = 150)
    private String title;

    @Column(name = "description", length = 500)
    private String description;

    /** Screening runtime in minutes; must be positive and is added to show start time to compute end time. */
    @Column(name = "duration_minutes", nullable = false)
    private int durationMinutes;

    /** Protected no-argument constructor required by JPA so Hibernate can instantiate proxies/rows via reflection. */
    protected Movie() {
    }

    public Movie(String title, String description, int durationMinutes) {
        this.title = title;
        this.description = description;
        this.durationMinutes = durationMinutes;
    }

    public Long getId() {
        return id;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public int getDurationMinutes() {
        return durationMinutes;
    }

    public void setDurationMinutes(int durationMinutes) {
        this.durationMinutes = durationMinutes;
    }
}